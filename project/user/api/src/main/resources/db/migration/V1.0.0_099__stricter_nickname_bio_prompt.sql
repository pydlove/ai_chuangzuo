【平台】
{{platform}}

【自媒体定位摘要】
{{positioning}}

【待检测昵称】
{{nickname}}

【判定维度】
1. 易读易记：是否简洁、朗朗上口、无歧义、无过长英文/数字混用。
2. 贴合定位：是否与平台、赛道、人设、内容支柱高度相关，让用户一眼知道账号价值。
3. 平台调性：是否符合该平台的命名习惯（小红书偏亲切/有身份感，公众号偏专业/IP 感，抖音偏短平快/有情绪，知乎偏真实/专家感，今日头条/百家号偏领域关键词，B 站偏兴趣/圈层感）。
4. 辨识度：是否有一定独特性，避免过于泛化或与已有大号重名风险。

【输出 JSON 结构】
{"fit": true/false, "reason": "判定理由，控制在 120 字以内", "suggestions": [{"nickname": "建议昵称 1", "bio": "一句话账号简介，30 字以内"}, {"nickname": "建议昵称 2", "bio": "一句话账号简介，30 字以内"}, {"nickname": "建议昵称 3", "bio": "一句话账号简介，30 字以内"}]}

要求：
1. fit=true 表示昵称契合定位，reason 说明契合点；fit=false 表示不够契合，reason 说明问题所在，并必须在 suggestions 给出 3 个建议昵称及简介。
2. suggestions 中的昵称必须与 platform 和 positioning 高度相关，不要泛泛而谈。
3. 建议昵称控制在 12 个汉字或 24 个字符以内，避免生僻字和敏感词。
4. bio 必须写成“平台账号简介/个人签名”风格，用一句话说明这个账号能为读者提供什么价值、内容方向或人设特点，控制在 30 字以内，符合 platform 调性，不要写成文章摘要、营销广告语、标签列表或 emoji 堆砌。
5. bio 中禁止出现 `｜`、`|`、`/`、`#`、`*`、emoji、特殊符号等任何形式的分隔符或装饰符；必须是完整、通顺、自然的一句话。
6. 不要输出类似“干货｜种草｜避雷”这种标签式堆砌，也不要用 bullet、列表或分段。
7. 只输出一个合法 JSON 对象，不要任何前言、说明、免责声明、markdown 标题或代码围栏。
8. 第一个字符必须是 {，最后一个字符必须是 }。'
WHERE prompt_code = 'platform_account_check_v1';

