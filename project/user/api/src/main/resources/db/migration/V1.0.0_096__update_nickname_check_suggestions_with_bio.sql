SET NAMES utf8mb4;

UPDATE c_ai_prompt
SET user_prompt = '请根据用户的自媒体定位，判断以下昵称是否与该定位契合；如果不契合，请给出 3 个更合适的昵称建议，每个建议包含昵称和对应账号简介。

【平台】
{{platform}}

【自媒体定位摘要】
{{positioning}}

【待检测昵称】
{{nickname}}

【判定维度】
1. 易读易记：是否简洁、朗朗上口、无歧义、无过长英文/数字混用。
2. 贴合定位：是否与平台、赛道、人设、内容支柱高度相关，让用户一眼知道账号价值。
3. 平台调性：是否符合该平台的命名习惯（小红书偏亲切/有身份感，公众号偏专业/IP 感，抖音偏短平快/有情绪，知乎偏真实/专家感，今日头条/百家号偏领域关键词，B 站偏兴趣/圈层感）。
4. 辨识度：是否有一定独特性，避免过于泛化或与已有大号重名风险。

【输出 JSON 结构】
{"fit": true/false, "reason": "判定理由，控制在 120 字以内", "suggestions": [{"nickname": "建议昵称 1", "bio": "简介 1，控制在 80 字以内"}, {"nickname": "建议昵称 2", "bio": "简介 2"}, {"nickname": "建议昵称 3", "bio": "简介 3"}]}

要求：
1. fit=true 表示昵称契合定位，reason 说明契合点；fit=false 表示不够契合，reason 说明问题所在，并必须在 suggestions 给出 3 个建议昵称及简介。
2. suggestions 中的昵称必须与 platform 和 positioning 高度相关，不要泛泛而谈。
3. 建议昵称控制在 12 个汉字或 24 个字符以内，避免生僻字和敏感词；简介说明账号价值、内容方向或人设特点。
4. 只输出一个合法 JSON 对象，不要任何前言、说明、免责声明、markdown 标题或代码围栏。
5. 第一个字符必须是 {，最后一个字符必须是 }。'
WHERE prompt_code = 'platform_account_check_v1';
