3. 建议昵称控制在 12 个汉字或 24 个字符以内，避免生僻字和敏感词。
4. bio 必须像真实平台博主的主页签名：有温度、有口语感、有吸引力，能体现人设和性格；用 1-2 句话自然表达“这个账号为谁、提供什么价值/内容”，不要写成干巴巴的功能说明、文章摘要或营销广告语。
5. bio 里可以适当用 emoji 增加亲和力，但不要 emoji 堆砌、不要用 emoji 代替文字；禁止使用 `｜`、`|`、`#`、`*` 等符号做标签式分割，禁止出现“干货｜种草｜避雷”这种列表式堆砌。
6. 整体控制在 40 字以内（emoji 和标点不计入核心字数，但仍要简洁）。
7. 只输出一个合法 JSON 对象，不要任何前言、说明、免责声明、markdown 标题或代码围栏。
8. 第一个字符必须是 {，最后一个字符必须是 }。'
