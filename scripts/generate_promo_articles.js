function buildDoc(title, blocks) {
  const children = []

  children.push(
    new Paragraph({
      text: title,
      heading: HeadingLevel.HEADING_1,
      alignment: AlignmentType.CENTER,
      spacing: { after: 400 }
    })
  )

  blocks.forEach((block) => {
    if (block.type === 'h2') {
      children.push(
        new Paragraph({
          text: block.text,
          heading: HeadingLevel.HEADING_2,
          spacing: { before: 360, after: 200 }
        })
      )
    } else {
      children.push(
        new Paragraph({
          children: [new TextRun({ text: block.text, size: 24 })],
          spacing: { after: 200, line: 360 },
          alignment: AlignmentType.JUSTIFIED
        })
      )
    }
  })

  return new Document({
    styles: {
      default: {
        document: {
          run: { font: 'Arial', size: 24 }
        }
      },
      paragraphStyles: [
        {
          id: 'Heading1',
          name: 'Heading 1',
          basedOn: 'Normal',
          next: 'Normal',
          quickFormat: true,
          run: { size: 36, bold: true, font: 'Arial', color: '1a1a1a' },
          paragraph: { spacing: { before: 0, after: 400 }, outlineLevel: 0 }
        },
        {
          id: 'Heading2',
          name: 'Heading 2',
          basedOn: 'Normal',
          next: 'Normal',
          quickFormat: true,
          run: { size: 28, bold: true, font: 'Arial', color: 'FF2442' },
          paragraph: { spacing: { before: 360, after: 200 }, outlineLevel: 1 }
        }
      ]
    },
    sections: [
      {
        properties: {
          page: {
            margin: { top: 1440, right: 1440, bottom: 1440, left: 1440 }
          }
        },
        headers: {
          default: new Header({
            children: [
              new Paragraph({
                children: [new TextRun({ text: '爱创作工坊', size: 18, color: '8c8c8c' })],
                alignment: AlignmentType.RIGHT
              })
            ]
          })
        },
        footers: {
          default: new Footer({
            children: [
              new Paragraph({
                children: [
                  new TextRun({ text: '第 ', size: 18, color: '8c8c8c' }),
                  new TextRun({ children: [PageNumber.CURRENT], size: 18, color: '8c8c8c' }),
                  new TextRun({ text: ' 页', size: 18, color: '8c8c8c' })
                ],
                alignment: AlignmentType.CENTER
              })
            ]
          })
        },
        children
      }
    ]
  })
}

async function main() {
  if (!fs.existsSync(OUT_DIR)) {
    fs.mkdirSync(OUT_DIR, { recursive: true })
  }

  for (const article of articles) {
    const doc = buildDoc(article.title, article.content)
    const buffer = await Packer.toBuffer(doc)
    const outPath = path.join(OUT_DIR, article.file)
    fs.writeFileSync(outPath, buffer)
    console.log(`已生成: ${outPath}`)
  }
}

main().catch((err) => {
  console.error(err)
  process.exit(1)
})
